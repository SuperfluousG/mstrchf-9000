import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const wasm=await readFile(new URL('../target/wasm32-unknown-unknown/release/mstrchf_browser.wasm',import.meta.url));
const module=await WebAssembly.compile(wasm);
assert.deepEqual(WebAssembly.Module.imports(module),[]);
const instance=await WebAssembly.instantiate(module,{});
const {memory,alloc,dealloc,run}=instance.exports;
const call=input=>{
  const bytes=new TextEncoder().encode(JSON.stringify(input));
  const p=alloc(bytes.length);
  new Uint8Array(memory.buffer,p,bytes.length).set(bytes);
  const packed=run(p,bytes.length);
  const outp=Number(packed&0xffffffffn),length=Number(packed>>32n);
  const text=new TextDecoder().decode(new Uint8Array(memory.buffer,outp,length));
  dealloc(p,bytes.length);dealloc(outp,length);
  const response=JSON.parse(text);assert.equal(response.ok,true,JSON.stringify(response));return response.value;
};
const now='2026-10-12T12:00:00Z';
const start=performance.now();
let state=call({op:'initialize',household_id:'hh_00000000000000000000000000000001',diner_id:'dn_00000000000000000000000000000001',zone:'Europe/London',today:'2026-10-12',now,demo:true});
assert.equal(state.snapshot.weeks.length,4);
const board=call({op:'board',state,now});
assert.ok(board.choices.length);
const week=board.week;
const command={schema_version:1,command_id:'cm_00000000000000000000000000000001',expected_snapshot_revision:state.snapshot.snapshot_revision,command:{kind:'save_week',data:{expected_week_revision:week.revision,week:{week_id:week.range.week_id,defaults_snapshot:week.defaults_snapshot,day_enabled:week.day_enabled,meal_type_enabled:week.meal_type_enabled,cells:week.cells,plan:board.choices[0].plan}}}};
const applied=call({op:'dispatch',state,command,command_json:JSON.stringify(command),now});
state=call({op:'validate_state',state:applied.state,now});
assert.equal(state.snapshot.weeks[0].plan.selections.length,1);
const replay=call({op:'dispatch',state,command,command_json:JSON.stringify(command),now});
assert.equal(replay.receipt.disposition,'replayed');
assert.equal(replay.receipt.response_digest,applied.receipt.response_digest);
console.log(JSON.stringify({wasm_bytes:wasm.length,imports:0,weeks:state.snapshot.weeks.length,choices:board.choices.length,saved_selections:state.snapshot.weeks[0].plan.selections.length,revision:state.snapshot.snapshot_revision,replay:'passed',duration_ms:Math.round(performance.now()-start)}));
