use serde::Serialize;
use ts_rs::TS;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, TS)]
pub enum SyntheticDataMode {
    #[serde(rename = "synthetic_development")]
    SyntheticDevelopment,
}
#[derive(Debug, Clone, PartialEq, Eq, Serialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum SupportedCommand {
    SaveHouseholdDraft,
    SetPrivacy,
    CancelJob,
    UpdateProfile,
    SaveWeek,
}

/// Shell-local support information, never command authority or domain eligibility.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, TS)]
pub struct ShellFeatures {
    #[ts(type = "1")]
    pub format_version: u8,
    pub data_mode: SyntheticDataMode,
    pub supported_commands: [SupportedCommand; 5],
    #[ts(type = "false")]
    pub production_runtime_enabled: bool,
}
impl ShellFeatures {
    pub fn synthetic() -> Self {
        Self {
            format_version: 1,
            data_mode: SyntheticDataMode::SyntheticDevelopment,
            supported_commands: [
                SupportedCommand::SaveHouseholdDraft,
                SupportedCommand::SetPrivacy,
                SupportedCommand::CancelJob,
                SupportedCommand::UpdateProfile,
                SupportedCommand::SaveWeek,
            ],
            production_runtime_enabled: false,
        }
    }
}
pub fn typescript() -> String {
    let cfg = ts_rs::Config::default();
    format!(
        "// Generated by shell-types from shell-local Rust declarations. Do not edit.\nexport {}\nexport {}\nexport {}\n",
        SyntheticDataMode::decl(&cfg),
        SupportedCommand::decl(&cfg),
        ShellFeatures::decl(&cfg)
    ) + &crate::receipt::typescript()
}

#[cfg(test)]
mod tests {
    #[test]
    fn support_has_the_exact_closed_shell_shape() {
        assert_eq!(
            serde_json::to_value(super::ShellFeatures::synthetic()).unwrap(),
            serde_json::json!({
                "format_version": 1, "data_mode": "synthetic_development",
                "supported_commands": ["save_household_draft", "set_privacy", "cancel_job", "update_profile", "save_week"],
                "production_runtime_enabled": false
            })
        );
    }
    #[test]
    fn checked_in_shell_types_are_generated_from_rust() {
        assert_eq!(
            std::fs::read_to_string(
                std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../app/generated/shell.ts")
            )
            .unwrap()
            .replace("\r\n", "\n"),
            super::typescript()
        );
    }
}
